"""
main.py
FastAPI backend for AI Data Analysis Chatbot & Dashboard.
Provides endpoints for uploading datasets (.csv / .xlsx), profiling, KPI calculation,
and AI-driven conversational querying with automatic Plotly visualization generation.
"""

import io
import uuid
from typing import Any, Dict, List, Optional
import pandas as pd
from fastapi import FastAPI, File, HTTPException, UploadFile, status
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

from analyzer import (
    clean_and_coerce_dataframe,
    extract_dataset_profile,
    format_schema_info_for_prompt,
    generate_initial_kpis,
)
from llm_engine import ask_data_agent

# Initialize FastAPI application
app = FastAPI(
    title="AI Data Analysis Chatbot & Dashboard API",
    description="Clean, modular FastAPI backend for AI-assisted data analysis and dynamic visualizations.",
    version="1.0.0",
)

# Enable CORS for frontend applications (React, Next.js, Vue, etc.)
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# In-memory session store keyed by session_id
# Structure: { session_id: { "df": pd.DataFrame, "filename": str, "profile": dict, "kpis": list, "schema_info": str } }
SESSION_STORE: Dict[str, Dict[str, Any]] = {}


# --- Pydantic Schemas ---
class ChatRequest(BaseModel):
    session_id: Optional[str] = Field(None, description="Optional session identifier obtained from /upload")
    query: str = Field(..., min_length=1, description="Analytical query or general question")


class ChatResponse(BaseModel):
    answer: str = Field(..., description="Textual explanation and summary of analysis")
    charts: List[str] = Field(default_factory=list, description="List of serialized Plotly chart JSON strings")
    chart_json: Optional[str] = Field(None, description="Serialized Plotly chart JSON string, or None if no chart")
    report_title: Optional[str] = Field(None, description="Dynamic statistical report title if report mode was activated")
    generated_code: str = Field(default="", description="Executable Python code generated by the AI agent")


class KPICard(BaseModel):
    label: str
    value: str
    description: str


class UploadResponse(BaseModel):
    session_id: str
    filename: str
    profile: Dict[str, Any]
    kpis: List[KPICard]


class HealthResponse(BaseModel):
    status: str
    active_sessions: int
    message: str


# --- API Routes ---
@app.get("/", response_model=HealthResponse, tags=["General"])
@app.get("/health", response_model=HealthResponse, tags=["General"])
async def health_check():
    """Health check endpoint to verify backend service status and active sessions."""
    return HealthResponse(
        status="ok",
        active_sessions=len(SESSION_STORE),
        message="AI Data Analysis Chatbot & Dashboard API is running smoothly.",
    )


@app.post("/upload", response_model=UploadResponse, tags=["Dataset"])
async def upload_dataset(file: UploadFile = File(...)):
    """
    Accepts a .csv or .xlsx file, loads it into Pandas, generates a session_id,
    extracts the dataset profile & initial KPIs, and returns them.
    """
    if not file.filename:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="No filename provided in upload.",
        )

    filename_lower = file.filename.lower()
    if not (filename_lower.endswith(".csv") or filename_lower.endswith(".xlsx") or filename_lower.endswith(".xls")):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Unsupported file format. Please upload a .csv or .xlsx file.",
        )

    try:
        contents = await file.read()
        if not contents:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Uploaded file is empty.",
            )

        # Parse CSV or Excel safely
        if filename_lower.endswith(".csv"):
            try:
                df = pd.read_csv(io.BytesIO(contents))
            except UnicodeDecodeError:
                # Fallback encoding if standard UTF-8 fails
                df = pd.read_csv(io.BytesIO(contents), encoding="latin1")
        else:
            df = pd.read_excel(io.BytesIO(contents))

        # Smart Type Cleaning: coerce string numbers like ".." or missing to proper numeric
        df = clean_and_coerce_dataframe(df)

    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Failed to read and parse dataset: {str(exc)}",
        ) from exc

    if df.empty or len(df.columns) == 0:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="The parsed dataset contains no rows or columns.",
        )

    # Generate session ID and compute profile & KPIs
    session_id = str(uuid.uuid4())
    try:
        profile = extract_dataset_profile(df)
        kpis = generate_initial_kpis(df)
        schema_info = format_schema_info_for_prompt(df, profile)
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to extract dataset profile: {str(exc)}",
        ) from exc

    # Store in memory
    SESSION_STORE[session_id] = {
        "df": df,
        "filename": file.filename,
        "profile": profile,
        "kpis": kpis,
        "schema_info": schema_info,
    }

    return UploadResponse(
        session_id=session_id,
        filename=file.filename,
        profile=profile,
        kpis=kpis,
    )


@app.post("/chat", response_model=ChatResponse, tags=["Chat"])
async def chat_with_data(request: ChatRequest):
    """
    Accepts JSON {"session_id": Optional[str], "query": str}.
    Operates in 3 smart modes:
    1. General Chat Mode (if session_id is None or question is general/conceptual)
    2. Single-Chart / Specific Data Query Mode (if dataset is active)
    3. Dynamic 2x2 Statistical Report Mode (if full analysis or dashboard requested)
    """
    clean_query = request.query.strip()
    if not clean_query:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Query cannot be empty.",
        )

    session = SESSION_STORE.get(request.session_id) if request.session_id else None
    df: Optional[pd.DataFrame] = session["df"] if session else None
    schema_info: Optional[str] = session["schema_info"] if session else None

    try:
        result = ask_data_agent(
            df=df,
            schema_info=schema_info,
            user_query=clean_query,
        )
        return ChatResponse(
            answer=result["answer"],
            charts=result.get("charts", []),
            chart_json=result.get("chart_json"),
            report_title=result.get("report_title"),
            generated_code=result.get("generated_code", ""),
        )
    except ValueError as val_err:
        # Configuration or parameter error (e.g., missing API key)
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(val_err),
        ) from val_err
    except PermissionError as perm_err:
        # Code execution violated sandbox rules
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Security constraint error: {str(perm_err)}",
        ) from perm_err
    except RuntimeError as run_err:
        # Retry loop failed or code execution crashed after retries
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=str(run_err),
        ) from run_err
    except Exception as exc:
        # Unhandled unexpected error
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Internal data agent error: {str(exc)}",
        ) from exc


@app.get("/session/{session_id}", response_model=UploadResponse, tags=["Dataset"])
async def get_session(session_id: str):
    """
    Retrieves the existing session metadata, profile, and initial KPIs.
    Helpful for frontend page reloads and state resumption.
    """
    session = SESSION_STORE.get(session_id)
    if not session:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Session '{session_id}' not found.",
        )

    return UploadResponse(
        session_id=session_id,
        filename=session["filename"],
        profile=session["profile"],
        kpis=session["kpis"],
    )


@app.delete("/session/{session_id}", tags=["Dataset"])
async def delete_session(session_id: str):
    """Removes a session from memory to free resources."""
    if session_id in SESSION_STORE:
        del SESSION_STORE[session_id]
        return {"message": f"Session '{session_id}' successfully removed."}
    raise HTTPException(
        status_code=status.HTTP_404_NOT_FOUND,
        detail=f"Session '{session_id}' not found.",
    )

